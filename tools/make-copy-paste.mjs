// 生成「一键复制」版文案：纯正文，去掉所有提示/配图说明/检查清单
// 每个平台文件夹里输出一个 `一键复制-粘贴用.txt`（UTF-8 无 BOM）
//
// 用法: node tools/make-copy-paste.mjs

import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';

import { assetsDir, asset } from './assets-dir.mjs';
const R = assetsDir;
const B = '无 BOM 纯 UTF-8';

const out = (folder, name, text) => {
  const p = `${R}/${folder}/${name}`;
  mkdirSync(`${R}/${folder}`, { recursive: true });
  writeFileSync(p, text.trimEnd() + '\n', { encoding: 'utf8' }); // 无 BOM
  console.log(`  ✅ ${folder}/${name}  ${text.length} 字`);
};

// 从手写正本派生（而不是内嵌一份副本）。
// 为什么需要这个：下面这些平台的文案是逐字打磨过的（口语化的开头、真实的缺点、
// 具体的事故细节），内嵌副本会随时间过期 —— 这个文件曾经把抖音的图文稿
// 覆盖回旧的视频分镜。派生则永远不会偏离正本。
const outFrom = (folder, name, parts) => {
  const chunks = [];
  for (const f of parts) {
    const p = `${R}/${folder}/${f}`;
    if (!existsSync(p)) {
      console.error(`  ❌ ${folder}/${f} 不存在 —— 正本缺失，停止派生（不写文件）`);
      process.exitCode = 1;
      return;
    }
    chunks.push(readFileSync(p, 'utf8').trim());
  }
  out(folder, name, chunks.join(`\n\n${'─'.repeat(48)}\n\n`));
};

const BAR = '─'.repeat(46);

